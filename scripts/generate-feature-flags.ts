import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { Eta } from "eta";
import { type ParseError, parse as parseJsonc, printParseErrorCode } from "jsonc-parser";
import * as v from "valibot";

const CHECK = process.argv.includes("--check");
const CI = process.env.CI === "true";
const SOURCE = "src/main/resources/feature-flags/feature-flags.jsonc";
const JAVA = "src/main/java/com/researchspace/featureflags/FeatureFlags.java";
const TS = "src/main/webapp/ui/src/featureFlags/generatedFeatureFlags.ts";
const MAX_NAME_LENGTH = 128;

const eta = new Eta({
  views: path.join(import.meta.dirname, "templates"),
  autoEscape: false,
  autoTrim: false,
});

/** True when the ISO date names a real calendar day; `v.isoDate` alone accepts 2026-02-31. */
const isCalendarDate = (value: string) => {
  const date = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
};

const required = (field: string) =>
  v.pipe(
    v.string(`must define ${field}`),
    v.check((value) => value.trim() !== "", `must define ${field}`),
  );

const FlagSchema = v.looseObject({
  name: v.pipe(v.string(), v.maxLength(MAX_NAME_LENGTH), v.regex(/^[a-z][a-zA-Z0-9]*$/, "invalid flag name")),
  default: v.optional(v.boolean("default must be boolean")),
  description: required("description"),
  owner: required("owner"),
  expires: v.pipe(
    v.string("must define expires"),
    v.isoDate("expires must be a valid ISO date"),
    v.check(isCalendarDate, "expires must be a valid ISO date"),
  ),
});

const ManifestSchema = v.looseObject({ flags: v.array(FlagSchema, "feature-flags.jsonc must contain a flags array") });

type Flag = v.InferOutput<typeof FlagSchema>;

const parseManifest = (text: string): unknown => {
  const errors: ParseError[] = [];
  const manifest: unknown = parseJsonc(text, errors, { allowTrailingComma: true });
  if (errors.length > 0) {
    const [{ error, offset }] = errors;
    throw new Error(`${SOURCE} is invalid JSONC at offset ${offset}: ${printParseErrorCode(error)}`);
  }
  return manifest;
};

const upperSnake = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();

const readManifest = async (): Promise<Flag[]> => {
  const result = v.safeParse(ManifestSchema, parseManifest(await readFile(SOURCE, "utf8")));
  if (!result.success) throw new Error(`${SOURCE} is invalid:\n${v.summarize(result.issues)}`);
  const { flags } = result.output;
  const seen = new Set<string>();
  const today = new Date(new Date().toISOString().slice(0, 10));
  for (const flag of flags) {
    if (seen.has(flag.name)) throw new Error(`Duplicate feature flag name: ${flag.name}`);
    seen.add(flag.name);
    if (CI && new Date(`${flag.expires}T00:00:00Z`) < today) {
      throw new Error(`Feature flag ${flag.name} expires has passed`);
    }
  }
  return flags;
};

const generatedBanner = (comment: string) => `${comment} Generated by scripts/generate-feature-flags.ts. Do not edit.`;

const renderJava = (flags: readonly Flag[]) =>
  eta.render("./FeatureFlags.java.eta", {
    banner: generatedBanner("//"),
    flags: flags.map((flag) => ({ name: flag.name, constant: upperSnake(flag.name) })),
  });

const renderTypescript = (flags: readonly Flag[]) =>
  eta.render("./generatedFeatureFlags.ts.eta", {
    banner: generatedBanner("//"),
    flags,
  });

const assertCurrentOrWrite = async (file: string, content: string) => {
  if (CHECK) {
    const current = await readFile(file, "utf8");
    if (current !== content) {
      throw new Error(`${file} is out of date. Run pnpm run feature-flags:generate.`);
    }
    return;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content);
};

const flags = await readManifest();
await assertCurrentOrWrite(JAVA, renderJava(flags));
await assertCurrentOrWrite(TS, renderTypescript(flags));
