package com.researchspace.dao.query;

import com.blazebit.persistence.BaseWhereBuilder;
import com.blazebit.persistence.CommonQueryBuilder;
import com.blazebit.persistence.CriteriaBuilder;
import com.blazebit.persistence.MultipleSubqueryInitiator;
import com.blazebit.persistence.SubqueryBuilder;
import com.researchspace.model.collection.CollectionDescription;
import com.researchspace.model.collection.FilterExpression;
import com.researchspace.model.collection.QueryConstraint;
import com.researchspace.model.collection.RelationshipReadAccess;
import com.researchspace.model.collection.RuntimeFieldSelection;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

/** Compiles a typed collection filter into a parameterized Blaze-Persistence predicate. */
public final class RsqlCollectionQuery {

  /** Maximum number of SQL LIKE/NOT LIKE predicates generated by one collection filter. */
  public static final int MAX_LIKE_PREDICATES = 50;

  public static final String FALSE_EXPRESSION = "1 = 0";

  private final CollectionDescription<?> description;
  private final String parameterPrefix;
  private final RsqlRelationshipCompiler relationships;
  private final RsqlExpressionCompiler expressions;

  public RsqlCollectionQuery(CollectionDescription<?> description, String alias) {
    this(description, alias, "rsql");
  }

  /**
   * Names generated parameters with {@code parameterPrefix}.
   *
   * <p>Use {@link #newCompilation()} to share generated names across predicates for one operation.
   * Independently compiled restrictions applied to the same query need distinct prefixes; combine
   * them through {@link Predicate#and} or {@link Predicate#or} to reject conflicting bindings.
   */
  public RsqlCollectionQuery(
      CollectionDescription<?> description, String alias, String parameterPrefix) {
    this(description, alias, parameterPrefix, RsqlFieldPredicateCompilerRegistry.builtIns());
  }

  public RsqlCollectionQuery(
      CollectionDescription<?> description,
      String alias,
      RsqlFieldPredicateCompilerRegistry compilers) {
    this(description, alias, "rsql", compilers);
  }

  /** Uses one immutable compiler registry throughout root and nested predicates. */
  public RsqlCollectionQuery(
      CollectionDescription<?> description,
      String alias,
      String parameterPrefix,
      RsqlFieldPredicateCompilerRegistry compilers) {
    this.description = Objects.requireNonNull(description, "Collection description");
    Objects.requireNonNull(compilers, "Comparison compilers").validate(description);
    if (parameterPrefix == null || parameterPrefix.isBlank()) {
      throw new IllegalArgumentException("Parameter prefix must not be blank");
    }
    this.parameterPrefix = parameterPrefix;
    this.relationships = new RsqlRelationshipCompiler(description, alias, compilers);
    this.expressions = new RsqlExpressionCompiler(description, alias, relationships, compilers);
  }

  /** Starts a name scope for predicates that will be composed into the same query. */
  public Compilation newCompilation() {
    return new Compilation();
  }

  public Predicate translate(FilterExpression filter) {
    return translate(filter, RelationshipReadAccess.none());
  }

  public Predicate translate(FilterExpression filter, RelationshipReadAccess targets) {
    return translate(filter, targets, RuntimeFieldSelection.empty());
  }

  public Predicate translate(
      FilterExpression filter, RelationshipReadAccess targets, RuntimeFieldSelection runtime) {
    return newCompilation().translate(filter, targets, runtime);
  }

  /** Compiles a server-built constraint without charging it to the caller complexity budget. */
  public Predicate translateTrusted(QueryConstraint constraint) {
    return translateTrusted(constraint, RelationshipReadAccess.none());
  }

  /** Compiles a relationship-aware server constraint without charging caller complexity limits. */
  public Predicate translateTrusted(QueryConstraint constraint, RelationshipReadAccess targets) {
    return newCompilation().translateTrusted(constraint, targets);
  }

  /** Compiles the SQL-level read rule for one described relationship. */
  public Predicate compileReadableRelationship(
      String relationshipName, RelationshipReadAccess targets) {
    return newCompilation().compileReadableRelationship(relationshipName, targets);
  }

  /**
   * One operation's name allocator. Use sequentially within that operation; this mutable session is
   * not thread-safe. Independent sessions start with the same names and do not share state.
   */
  public final class Compilation {
    private final RsqlCompilationState.Names names =
        new RsqlCompilationState.Names(parameterPrefix);

    private Compilation() {}

    public Predicate translate(
        FilterExpression filter, RelationshipReadAccess targets, RuntimeFieldSelection runtime) {
      if (filter == null) {
        return null;
      }
      RsqlCompilationState state = new RsqlCompilationState(names, targets, runtime, true);
      return compile(filter, state);
    }

    public Predicate translate(FilterExpression filter, RelationshipReadAccess targets) {
      return translate(filter, targets, RuntimeFieldSelection.empty());
    }

    public Predicate translateTrusted(QueryConstraint constraint, RelationshipReadAccess targets) {
      if (constraint == null) {
        return null;
      }
      RsqlCompilationState state =
          new RsqlCompilationState(names, targets, RuntimeFieldSelection.empty(), false);
      return compileTrusted(constraint, state);
    }

    public Predicate compileReadableRelationship(
        String relationshipName, RelationshipReadAccess targets) {
      RsqlCompilationState state =
          new RsqlCompilationState(
              names,
              Objects.requireNonNull(targets, "Target access"),
              RuntimeFieldSelection.empty(),
              false);
      return state.predicate(
          relationships.compileReadableRelationship(
              description.requireRelationship(relationshipName), state));
    }
  }

  Predicate compile(FilterExpression filter, RsqlCompilationState state) {
    return state.predicate(expressions.compile(filter, state));
  }

  Predicate compileTrusted(QueryConstraint constraint, RsqlCompilationState state) {
    return state.predicate(expressions.compileConstraint(constraint, state));
  }

  static <T> void mergeMappings(Map<String, T> destination, Map<String, T> source, String kind) {
    source.forEach(
        (name, value) -> {
          if (destination.containsKey(name) && !Objects.equals(destination.get(name), value)) {
            throw new IllegalArgumentException("Conflicting " + kind + " name: " + name);
          }
        });
    destination.putAll(source);
  }

  /**
   * One correlated subquery, kept out of the expression text.
   *
   * <p>Blaze's expression parser accepts no subquery, so a subquery must be built through {@code
   * whereExpressionSubqueries} and referenced from the expression by name.
   */
  public record Subquery(
      Class<?> entityType, String alias, String whereExpression, Map<String, Subquery> subqueries) {

    public Subquery {
      subqueries = Map.copyOf(subqueries);
    }

    public Subquery(Class<?> entityType, String alias, String whereExpression) {
      this(entityType, alias, whereExpression, Map.of());
    }
  }

  public record Predicate(
      String expression,
      Map<String, Object> parameters,
      Map<String, Subquery> subqueries,
      int callerLikePredicateCount) {

    public Predicate {
      if (callerLikePredicateCount < 0) {
        throw new IllegalArgumentException("Caller LIKE predicate count must not be negative");
      }
      parameters = Map.copyOf(parameters);
      subqueries = Map.copyOf(subqueries);
    }

    /** Preserves the original constructor for predicates that contain no caller LIKE count. */
    public Predicate(
        String expression, Map<String, Object> parameters, Map<String, Subquery> subqueries) {
      this(expression, parameters, subqueries, 0);
    }

    public Predicate(String expression, Map<String, Object> parameters) {
      this(expression, parameters, Map.of(), 0);
    }

    /**
     * Combines present predicates and rejects bindings that would silently change their meaning.
     */
    public static Predicate and(Predicate... predicates) {
      return compose(" AND ", predicates);
    }

    /**
     * Combines present predicates and rejects bindings that would silently change their meaning.
     */
    public static Predicate or(Predicate... predicates) {
      return compose(" OR ", predicates);
    }

    private static Predicate compose(String separator, Predicate... predicates) {
      List<String> expressions = new ArrayList<>();
      Map<String, Object> parameters = new LinkedHashMap<>();
      Map<String, Subquery> subqueries = new LinkedHashMap<>();
      int likeCount = 0;
      Predicate first = null;
      for (Predicate predicate : predicates) {
        if (predicate == null) {
          continue;
        }
        if (first == null) {
          first = predicate;
        }
        expressions.add("(" + predicate.expression() + ")");
        mergeMappings(parameters, predicate.parameters(), "parameter");
        mergeMappings(subqueries, predicate.subqueries(), "subquery");
        likeCount = Math.addExact(likeCount, predicate.callerLikePredicateCount());
      }
      if (expressions.size() < 2) {
        return first;
      }
      return new Predicate(String.join(separator, expressions), parameters, subqueries, likeCount);
    }

    /**
     * Applies the expression and all nested subqueries, then binds parameters on the root query.
     */
    public void applyTo(BaseWhereBuilder<?> where, CommonQueryBuilder<?> root) {
      applyWhere(where, expression, subqueries);
      parameters.forEach(root::setParameter);
    }

    public void applyTo(CriteriaBuilder<?> query) {
      applyTo(query, query);
    }

    private static void applyWhere(
        BaseWhereBuilder<?> where, String expression, Map<String, Subquery> subqueries) {
      if (subqueries.isEmpty()) {
        where.whereExpression(expression);
        return;
      }
      MultipleSubqueryInitiator<?> initiator = where.whereExpressionSubqueries(expression);
      subqueries.forEach(
          (name, subquery) -> {
            SubqueryBuilder<?> builder =
                initiator.with(name).from(subquery.entityType(), subquery.alias()).select("1");
            applyWhere(builder, subquery.whereExpression(), subquery.subqueries());
            builder.end();
          });
      initiator.end();
    }
  }
}
