import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { camel } from "orval";
import { type OpenApiDocument, operationsOf, orvalTypeName, type SchemaObject } from "./openapi.ts";

const header = "// Generated by scripts/api-v2-valibot/filters.ts. Do not edit.\n";
const tokens: ReadonlySet<string> = new Set([
  "==",
  "!=",
  "=gt=",
  "=ge=",
  "=lt=",
  "=le=",
  "=in=",
  "=out=",
  "=contains=",
  "=like=",
  "=exists=",
]);

interface FilterSelector {
  operators: string[];
  schema: SchemaObject;
}
interface FilterMetadata {
  selectors: Record<string, FilterSelector>;
}
interface ParameterObject {
  name?: string;
  in?: string;
  $ref?: string;
  "x-rspace-filter"?: { $ref?: string };
}

const filtersOf = (document: OpenApiDocument) =>
  (document.components?.["x-rspace-filters"] ?? {}) as Record<string, FilterMetadata>;
const parametersOf = (document: OpenApiDocument) =>
  (document.components?.parameters ?? {}) as Record<string, ParameterObject>;

function filterResource(document: OpenApiDocument, parameter: ParameterObject, location: string): string {
  const ref = parameter["x-rspace-filter"]?.$ref;
  const prefix = "#/components/x-rspace-filters/";
  if (!ref?.startsWith(prefix)) throw new Error(`${location}: Unsupported filter reference ${ref}`);
  const resource = ref.slice(prefix.length);
  if (!Object.hasOwn(filtersOf(document), resource)) throw new Error(`${location}: Missing filter ${resource}`);
  return resource;
}

/** Component `where` parameters that carry filter metadata, keyed by component name. */
export function filteredWhereParameters(document: OpenApiDocument): Map<string, string> {
  const result = new Map<string, string>();
  for (const [name, parameter] of Object.entries(parametersOf(document))) {
    if (parameter.in === "query" && parameter.name === "where" && parameter["x-rspace-filter"])
      result.set(name, filterResource(document, parameter, `components.parameters.${name}`));
  }
  return result;
}

/** Operation IDs whose `where` parameter carries filter metadata, mapped to the filter resource. */
export function filteredWhereOperations(document: OpenApiDocument): Map<string, string> {
  const components = parametersOf(document);
  const result = new Map<string, string>();
  for (const [path, item] of Object.entries(document.paths ?? {}))
    for (const [, operation] of operationsOf(item)) {
      for (const entry of (operation.parameters ?? []) as ParameterObject[]) {
        const parameter = entry.$ref ? components[entry.$ref.split("/").at(-1) ?? ""] : entry;
        if (parameter?.in !== "query" || parameter.name !== "where" || !parameter["x-rspace-filter"]) continue;
        if (!operation.operationId) throw new Error(`${path}: Missing operationId`);
        result.set(operation.operationId, filterResource(document, parameter, `${path}.where`));
      }
    }
  return result;
}

function valueType(schema: SchemaObject, location: string): string {
  if (Array.isArray(schema.enum)) {
    const values = schema.enum.filter((value) => value !== null);
    if (!values.length || !values.every((value) => typeof value === "string" || typeof value === "number"))
      throw new Error(`${location}: Unsupported enum`);
    return values.map((value) => JSON.stringify(value)).join(" | ");
  }
  const types = (Array.isArray(schema.type) ? schema.type : [schema.type]).filter((type) => type !== "null");
  if (types.length !== 1) throw new Error(`${location}: Unsupported filter value type ${JSON.stringify(schema.type)}`);
  const [type] = types;
  if (type === "integer" || type === "number") return "number";
  if (type === "boolean") return "boolean";
  if (type === "string") return schema.format === "date-time" || schema.format === "date" ? "string | Date" : "string";
  throw new Error(`${location}: Unsupported filter value type ${type}`);
}

/** Emits per-resource selector metadata types from `components.x-rspace-filters`. */
export function generateFilterTypes(document: OpenApiDocument): string {
  const resources = Object.entries(filtersOf(document)).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const entries = resources.map(([resource, filter]) => {
    if (!/^[A-Za-z_$][\w$]*$/.test(resource)) throw new Error(`Filter name ${resource} is not a TypeScript identifier`);
    // A selector with no operators is listed for documentation but cannot be filtered on.
    const selectors = Object.entries(filter.selectors ?? {})
      .filter(([, metadata]) => metadata.operators?.length)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([selector, metadata]) => {
        const location = `x-rspace-filters.${resource}.${selector}`;
        const operators = [...new Set(metadata.operators)];
        if (operators.some((operator) => !tokens.has(operator)))
          throw new Error(`${location}: Unsupported operators ${JSON.stringify(metadata.operators)}`);
        return `    ${JSON.stringify(selector)}: { operators: ${operators.map((operator) => JSON.stringify(operator)).join(" | ")}; value: ${valueType(metadata.schema ?? {}, location)} };`;
      });
    return `  ${resource}: {\n${selectors.join("\n")}\n  };`;
  });
  return `${header}/** Filterable selectors per REST API v2 filter, with their allowed RSQL operators and value types. */\nexport interface ApiV2FilterFields {\n${entries.join("\n")}\n}\n`;
}

/** Narrows Orval's `export type <Name>Parameter = string;` model to the filter's \`ApiV2Where\` type. */
export function rewriteWhereModel(source: string, componentName: string, resource: string): string {
  const typeName = `${orvalTypeName(componentName)}Parameter`;
  const declaration = `export type ${typeName} = string;`;
  if (!source.includes(declaration)) throw new Error(`Unexpected model for ${componentName}: ${declaration} not found`);
  const narrowed = source.replace(declaration, `export type ${typeName} = ApiV2Where<"${resource}">;`);
  const importLine = 'import type { ApiV2Where } from "../../apiV2Where";\n';
  const docStart = narrowed.indexOf("\n/**", narrowed.indexOf("*/") + 2);
  return docStart < 0
    ? `${importLine}\n${narrowed}`
    : `${narrowed.slice(0, docStart + 1)}${importLine}${narrowed.slice(docStart + 1)}`;
}

const modelFile = (componentName: string) => `${camel(`${orvalTypeName(componentName)}Parameter`)}.ts`;

export async function generateFilterFiles(input: string, generated: string): Promise<void> {
  const document: OpenApiDocument = JSON.parse(await readFile(input, "utf8"));
  const written = [resolve(generated, "filters.ts")];
  await writeFile(written[0], generateFilterTypes(document));
  for (const [componentName, resource] of filteredWhereParameters(document)) {
    const path = resolve(generated, "models", modelFile(componentName));
    await writeFile(path, rewriteWhereModel(await readFile(path, "utf8"), componentName, resource));
    written.push(path);
  }
  execFileSync("pnpm", ["exec", "biome", "check", "--write", ...written], { stdio: "inherit" });
}

