import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { isPlainObject, sortBy, uniq } from "es-toolkit";
import type { OpenApiDocument } from "orval";
import { camel } from "orval";
import { apiV2WhereOperators } from "../../src/modules/common/api/v2/apiV2Where.ts";
import { biomeWrite } from "./biome.ts";
import { operationsOf, orvalTypeName, parseOpenApiDocument, type SchemaObject } from "./openapi.ts";

const header = "// Generated by scripts/api-v2-valibot/filters.ts. Do not edit.\n";
const tokens: ReadonlySet<string> = new Set(Object.values(apiV2WhereOperators));
const selectorName = /^[A-Za-z][A-Za-z0-9_-]*(?:\.[A-Za-z][A-Za-z0-9_-]*)?$/;
const compositionKeywords = ["oneOf", "anyOf", "allOf", "$ref"] as const;

/** The kind of value a selector compares against. `enum` selectors list their values. */
export type FilterValueKind = "string" | "number" | "boolean" | "dateTime" | "enum";

/** One selector of a REST API v2 filter, classified once for every generated output that reads filters. */
export interface FilterCatalogSelector {
  kind: FilterValueKind;
  values?: (string | number)[];
  /** Empty for a selector that is listed for documentation but cannot be filtered on. */
  operators: string[];
  wildcards: boolean;
  /** Passed through unchecked, for a consumer that validates it. */
  picker?: unknown;
}
/** Every filter in `components.x-rspace-filters`, keyed by filter name, then by selector. */
export type FilterCatalog = Record<string, Record<string, FilterCatalogSelector>>;

interface FilterMetadata {
  selectors?: Record<string, unknown>;
}
interface ParameterObject {
  name?: string;
  in?: string;
  $ref?: string;
  "x-rspace-filter"?: { $ref?: string };
}
const filtersOf = (document: OpenApiDocument) =>
  (document.components?.["x-rspace-filters"] ?? {}) as Record<string, FilterMetadata>;
const parametersOf = (document: OpenApiDocument) =>
  (document.components?.parameters ?? {}) as Record<string, ParameterObject>;

function filterResource(document: OpenApiDocument, parameter: ParameterObject, location: string): string {
  const ref = parameter["x-rspace-filter"]?.$ref;
  const prefix = "#/components/x-rspace-filters/";
  if (!ref?.startsWith(prefix)) throw new Error(`${location}: Unsupported filter reference ${ref}`);
  const resource = ref.slice(prefix.length);
  if (!Object.hasOwn(filtersOf(document), resource)) throw new Error(`${location}: Missing filter ${resource}`);
  return resource;
}

/** Component `where` parameters that carry filter metadata, keyed by component name. */
export function filteredWhereParameters(document: OpenApiDocument): Map<string, string> {
  const result = new Map<string, string>();
  for (const [name, parameter] of Object.entries(parametersOf(document))) {
    if (parameter.in === "query" && parameter.name === "where" && parameter["x-rspace-filter"])
      result.set(name, filterResource(document, parameter, `components.parameters.${name}`));
  }
  return result;
}

/** Operation IDs whose `where` parameter carries filter metadata, mapped to the filter resource. */
export function filteredWhereOperations(document: OpenApiDocument): Map<string, string> {
  const components = parametersOf(document);
  const result = new Map<string, string>();
  for (const [path, item] of Object.entries(document.paths ?? {}))
    for (const [, operation] of operationsOf(item)) {
      for (const entry of (operation.parameters ?? []) as ParameterObject[]) {
        const parameter = entry.$ref ? components[entry.$ref.split("/").at(-1) ?? ""] : entry;
        if (parameter?.in !== "query" || parameter.name !== "where" || !parameter["x-rspace-filter"]) continue;
        if (!operation.operationId) throw new Error(`${path}: Missing operationId`);
        result.set(operation.operationId, filterResource(document, parameter, `${path}.where`));
      }
    }
  return result;
}

const scalarTypes: Readonly<Record<string, "string" | "number" | "boolean">> = {
  string: "string",
  integer: "number",
  number: "number",
  boolean: "boolean",
};

function valueKind(schema: SchemaObject, location: string): Pick<FilterCatalogSelector, "kind" | "values"> {
  const composition = compositionKeywords.find((keyword) => Object.hasOwn(schema, keyword));
  if (composition) throw new Error(`${location}: Unsupported filter value schema with ${composition}`);
  if (schema.format !== undefined && typeof schema.format !== "string")
    throw new Error(`${location}: format must be a string`);
  // One scalar type, optionally paired with one "null"; an enum must also declare it.
  const declared = Array.isArray(schema.type) ? schema.type : [schema.type];
  const types = declared.filter((type) => type !== "null");
  const scalar =
    declared.length - types.length <= 1 &&
    types.length === 1 &&
    typeof types[0] === "string" &&
    Object.hasOwn(scalarTypes, types[0])
      ? scalarTypes[types[0]]
      : undefined;
  if (scalar === undefined)
    throw new Error(`${location}: Unsupported filter value type ${JSON.stringify(schema.type)}`);
  if (schema.enum !== undefined) {
    const values = Array.isArray(schema.enum) ? schema.enum.filter((value) => value !== null) : [];
    if (scalar === "boolean" || !values.length || !values.every((value) => typeof value === scalar))
      throw new Error(`${location}: Unsupported enum`);
    return { kind: "enum", values: values as (string | number)[] };
  }
  if (scalar === "string" && schema.format === "date-time") return { kind: "dateTime" };
  return { kind: scalar };
}

function catalogSelector(metadata: unknown, location: string): FilterCatalogSelector {
  if (!isPlainObject(metadata)) throw new Error(`${location}: Expected an object`);
  const { operators, schema, wildcards, picker, title, viaTitle } = metadata;
  if (!Array.isArray(operators) || operators.some((operator) => typeof operator !== "string" || !tokens.has(operator)))
    throw new Error(`${location}: Unsupported operators ${JSON.stringify(operators)}`);
  if (typeof wildcards !== "boolean") throw new Error(`${location}: wildcards must be a boolean`);
  // Titles are English documentation; the UI labels selectors from its own catalogs.
  for (const [name, value] of Object.entries({ title, viaTitle }))
    if (value !== undefined && typeof value !== "string") throw new Error(`${location}: ${name} must be a string`);
  if (!isPlainObject(schema)) throw new Error(`${location}: Missing value schema`);
  return {
    ...valueKind(schema as SchemaObject, location),
    operators: uniq(operators as string[]),
    wildcards,
    ...(picker === undefined ? {} : { picker }),
  };
}

/**
 * Classifies every selector of every filter once, from the raw document, so every generated output that reads
 * filters (`generated/filters.ts` first) sees the same selectors.
 */
export function filterCatalog(document: OpenApiDocument): FilterCatalog {
  return Object.fromEntries(
    sortBy(Object.entries(filtersOf(document)), [([filter]) => filter]).map(([filter, metadata]) => {
      if (!/^[A-Za-z_$][\w$]*$/.test(filter)) throw new Error(`Filter name ${filter} is not a TypeScript identifier`);
      if (!isPlainObject(metadata?.selectors))
        throw new Error(`x-rspace-filters.${filter}: selectors must be an object`);
      const selectors = sortBy(Object.entries(metadata.selectors), [([selector]) => selector]).map(
        ([selector, selectorMetadata]) => {
          const location = `x-rspace-filters.${filter}.${selector}`;
          if (!selectorName.test(selector)) throw new Error(`${location}: Unsupported selector name`);
          return [selector, catalogSelector(selectorMetadata, location)] as const;
        },
      );
      return [filter, Object.fromEntries(selectors)];
    }),
  );
}

function valueType({ kind, values }: FilterCatalogSelector): string {
  switch (kind) {
    case "enum":
      return (values ?? []).map((value) => JSON.stringify(value)).join(" | ");
    case "dateTime":
      return "string | Temporal.Instant";
    default:
      return kind;
  }
}

/** Emits per-resource selector metadata types from `components.x-rspace-filters`. */
export function generateFilterTypes(document: OpenApiDocument): string {
  const catalog = filterCatalog(document);
  const usesInstant = Object.values(catalog).some((selectors) =>
    Object.values(selectors).some((selector) => selector.kind === "dateTime" && selector.operators.length),
  );
  const imports = usesInstant ? 'import type { Temporal } from "@js-temporal/polyfill";\n' : "";
  const entries = Object.entries(catalog).map(([filter, selectors]) => {
    // A selector with no operators is listed for documentation but cannot be filtered on.
    const fields = Object.entries(selectors)
      .filter(([, selector]) => selector.operators.length)
      .map(
        ([name, selector]) =>
          `    ${JSON.stringify(name)}: { operators: ${selector.operators.map((operator) => JSON.stringify(operator)).join(" | ")}; value: ${valueType(selector)} };`,
      );
    return `  ${filter}: {\n${fields.join("\n")}\n  };`;
  });
  return `${header}${imports}/** Filterable selectors per REST API v2 filter, with their allowed RSQL operators and value types. */\nexport interface ApiV2FilterFields {\n${entries.join("\n")}\n}\n`;
}

/** Narrows Orval's `export type <Name>Parameter = string;` model to the filter's \`ApiV2Where\` type. */
export function rewriteWhereModel(source: string, componentName: string, resource: string): string {
  const typeName = `${orvalTypeName(componentName)}Parameter`;
  const declaration = `export type ${typeName} = string;`;
  if (!source.includes(declaration)) throw new Error(`Unexpected model for ${componentName}: ${declaration} not found`);
  const narrowed = source.replace(declaration, `export type ${typeName} = ApiV2Where<"${resource}">;`);
  const importLine = 'import type { ApiV2Where } from "../../apiV2Where";\n';
  const docStart = narrowed.indexOf("\n/**", narrowed.indexOf("*/") + 2);
  return docStart < 0
    ? `${importLine}\n${narrowed}`
    : `${narrowed.slice(0, docStart + 1)}${importLine}${narrowed.slice(docStart + 1)}`;
}

const modelFile = (componentName: string) => `${camel(`${orvalTypeName(componentName)}Parameter`)}.ts`;

export async function generateFilterFiles(input: string, generated: string): Promise<void> {
  const document = parseOpenApiDocument(await readFile(input, "utf8"));
  const written = [resolve(generated, "filters.ts")];
  await writeFile(written[0], generateFilterTypes(document));
  for (const [componentName, resource] of filteredWhereParameters(document)) {
    const path = resolve(generated, "models", modelFile(componentName));
    await writeFile(path, rewriteWhereModel(await readFile(path, "utf8"), componentName, resource));
    written.push(path);
  }
  biomeWrite(written);
}

if (import.meta.main) {
  const ui = resolve(import.meta.dirname, "../..");
  await generateFilterFiles(
    resolve(ui, "src/modules/common/api/v2/openapi.generated.json"),
    resolve(ui, "src/modules/common/api/v2/generated"),
  );
}
