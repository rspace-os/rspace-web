import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const requireOrval = createRequire(createRequire(import.meta.url).resolve("orval"));
const { getTagKey } = requireOrval("@orval/core");
const methods = new Set(["get", "post", "put", "patch", "delete", "head", "options", "trace"]);
const slots = {
  LIST: "list",
  COUNT: "count",
  READ: "get",
  CREATE: "create",
  UPDATE: "update",
  DELETE: "delete",
  BULK_CREATE: "createMany",
  BULK_UPDATE: "updateMany",
  BULK_DELETE: "deleteMany",
  ACCESS_READ: "access",
  ACCESS_REPLACE: "replaceAccess",
  ACCESS_LEAVE: "leaveAccess",
  ACCESS_GRANTEE_SEARCH: "grantees",
  AUDIT_LIST: "audit",
  RUNTIME_FIELDS: "runtimeFields",
};
const slotOrder = Object.values(slots);
const reads = new Set(["list", "count", "get", "access", "grantees", "audit", "runtimeFields"]);

export function collectionOperations(document) {
  const resources = new Map();
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(item)) {
      if (!methods.has(method)) continue;
      const kind = operation["x-rspace-operation"];
      if (kind === "CUSTOM") continue;
      if (!Object.hasOwn(slots, kind))
        throw new Error(`${path}: ${kind == null ? "Untagged operation" : `Unknown operation kind ${kind}`}`);
      const slot = slots[kind];
      if (!operation.operationId || !operation.tags?.length) throw new Error(`Invalid resource operation: ${path}`);
      for (const resource of operation.tags) {
        const entries = resources.get(resource) ?? new Map();
        if (entries.has(slot)) throw new Error(`Duplicate slot ${resource}.${slot}`);
        const tag = getTagKey(resource);
        entries.set(slot, {
          id: operation.operationId,
          file: `./${tag}/${tag}.ts`,
          read: reads.has(slot),
        });
        resources.set(resource, entries);
      }
    }
  }
  return resources;
}

export async function generateResources(document, readTarget) {
  const resources = collectionOperations(document);
  const files = [
    ...new Set([...resources.values()].flatMap((entries) => [...entries.values()].map(({ file }) => file))),
  ].sort();
  const sources = new Map();
  for (const file of files) sources.set(file, await readTarget(file));
  const imports = files.map((file, index) => `import * as resource${index} from ${JSON.stringify(file)};`);
  const entries = [...resources]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, operations]) => {
      const properties = [...operations]
        .sort(([a], [b]) => slotOrder.indexOf(a) - slotOrder.indexOf(b))
        .map(([slot, { id, file, read }]) => {
          const key = `get${id[0].toUpperCase()}${id.slice(1)}QueryKey`;
          for (const target of read ? [id, key] : [id]) {
            if (!new RegExp(`export (?:const|function) ${target}\\b`).test(sources.get(file)))
              throw new Error(`Missing import target ${target} in ${file}`);
          }
          const alias = `resource${files.indexOf(file)}`;
          return `    ${slot}: ${read ? `{ request: ${alias}.${id}, queryKey: ${alias}.${key} }` : `${alias}.${id}`},`;
        });
      return `  ${JSON.stringify(name)}: {\n    name: ${JSON.stringify(name)},\n${properties.join("\n")}\n  } satisfies ApiV2ResourceEntry<${JSON.stringify(name)}, ApiV2OperationSet>,`;
    });
  const source = `// Generated by scripts/api-v2-valibot/resources.mjs. Do not edit.\nimport type { ApiV2OperationSet, ApiV2ResourceEntry } from "../apiV2Resources";\n${imports.join("\n")}\n\nexport const apiV2Resources = {\n${entries.join("\n")}\n};\n`;
  return execFileSync("pnpm", ["exec", "biome", "format", "--stdin-file-path=apiV2Resources.ts"], {
    input: source,
    encoding: "utf8",
  });
}

export async function generateResourceFile(input, output) {
  const document = JSON.parse(await readFile(input, "utf8"));
  const source = await generateResources(document, (file) => readFile(resolve(output, file), "utf8"));
  await writeFile(resolve(output, "apiV2Resources.ts"), source);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const ui = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
  await generateResourceFile(
    resolve(ui, "src/modules/common/api/v2/openapi.generated.json"),
    resolve(ui, "src/modules/common/api/v2/generated"),
  );
}
