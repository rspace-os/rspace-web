import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { OpenApiRequestBodyObject, OpenApiResponseObject } from "orval";
import {
  type Content,
  isReference,
  type OpenApiDocument,
  operationsOf,
  orvalOperationName,
  orvalTypeName,
  parseOpenApiDocument,
  type ReferenceObject,
  responsesOf,
  type SchemaObject,
  type SchemaOrReference,
} from "./openapi.ts";
import { assertSupportedSpec } from "./preflight.ts";

const json = JSON.stringify;
const header = "// Generated by scripts/api-v2-valibot/generate.ts. Do not edit.\n";

export interface GeneratedSources {
  native: string;
  schemas: string;
  operations: string;
}

/** Register Orval's reusable Valibot output without translating schema validation. */
export function generate(
  document: OpenApiDocument,
  nativeSource: string,
  { modelImport = "../models" }: { modelImport?: string } = {},
): GeneratedSources {
  assertSupportedSpec(document);
  if (typeof nativeSource !== "string") throw new Error("Orval native Valibot output is required");
  const components = document.components?.schemas ?? {};
  function resolveObject<T extends object>(
    value: T | ReferenceObject | undefined,
    section: "schemas" | "requestBodies" | "responses",
    seen = new Set<string>(),
  ): T | undefined {
    if (!isReference(value)) return value;
    const prefix = `#/components/${section}/`;
    const ref = value.$ref;
    if (!ref.startsWith(prefix) || seen.has(ref)) throw new Error(`Unsupported reference ${ref}`);
    const target = document.components?.[section]?.[ref.slice(prefix.length)] as T | ReferenceObject | undefined;
    if (!target) throw new Error(`Missing reference ${ref}`);
    return resolveObject(target, section, new Set([...seen, ref]));
  }
  function binary(schema: SchemaOrReference) {
    return typeof schema !== "boolean" && resolveObject<SchemaObject>(schema, "schemas")?.format === "binary";
  }
  function jsonContent(content: Content | undefined, location: string) {
    return Object.entries(content ?? {}).filter(([media, entry]) => {
      if (!/^application\/(?:[\w.+-]+\+)?json$/i.test(media)) return false;
      if (!entry.schema) throw new Error(`${location}: Missing JSON schema for ${media}`);
      return !binary(entry.schema);
    });
  }
  // Sort schema keys when comparing: order cannot change media equivalence.
  function signature(schema: SchemaOrReference) {
    function sorted(value: unknown): unknown {
      if (Array.isArray(value)) return value.map(sorted);
      if (!value || typeof value !== "object") return value;
      return Object.fromEntries(
        Object.entries(value)
          .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
          .map(([key, child]) => [key, sorted(child)]),
      );
    }
    return json(sorted(schema));
  }
  const ids = new Set<string>(),
    operations: string[] = [];
  for (const [path, item] of Object.entries(document.paths ?? {}))
    for (const [, op] of operationsOf(item)) {
      const id = op.operationId;
      if (!id || ids.has(id)) throw new Error(`${path}: Missing or duplicate operationId ${id}`);
      ids.add(id);
      const name = orvalTypeName(orvalOperationName(id)),
        security = op.security ?? document.security ?? [];
      const parts: string[] = [];
      if (!security.length) parts.push("public: true");
      else if (
        security.every(
          (requirement) => Object.keys(requirement).length === 1 && Object.hasOwn(requirement, "browserSession"),
        )
      )
        parts.push("session: true");
      const requestContent = resolveObject<OpenApiRequestBodyObject>(op.requestBody, "requestBodies")?.content;
      const requests = jsonContent(requestContent, `${id}.request`);
      if (
        requests.length &&
        new Set(Object.values(requestContent ?? {}).flatMap((entry) => (entry.schema ? [signature(entry.schema)] : [])))
          .size > 1
      )
        throw new Error(`Distinct JSON request schemas require synthetic operations: ${id}`);
      if (requests.length) parts.push(`request: native.${name}Body`);
      const responses: string[] = [],
        signatures = new Set<string>(),
        allSuccessSchemas = new Set<string>();
      for (const [status, response] of responsesOf(op)) {
        if (!/^2(?:\d\d|XX)$/.test(status) || status === "204") continue;
        const responseContent = resolveObject<OpenApiResponseObject>(response, "responses")?.content;
        for (const entry of Object.values(responseContent ?? {}))
          if (entry.schema) allSuccessSchemas.add(signature(entry.schema));
        const entries = jsonContent(responseContent, `${id}.responses.${status}`);
        for (const [, entry] of entries) if (entry.schema) signatures.add(signature(entry.schema));
        if (entries.length)
          responses.push(
            `${json(status)}: {${entries.map(([media]) => `${json(media)}: native.${name}Response`).join(", ")}}`,
          );
      }
      if (signatures.size && allSuccessSchemas.size > 1)
        throw new Error(`Distinct JSON success schemas require synthetic operations: ${id}`);
      parts.push(`responses: {${responses.join(", ")}}`);
      operations.push(`${json(id)}: {${parts.join(", ")}}`);
    }
  const native = nativeSource;
  const exports = new Set([...native.matchAll(/export const (\w+)/g)].map((match) => match[1]));
  const names = Object.keys(components).sort();
  for (const name of names) if (!exports.has(orvalTypeName(name))) throw new Error(`Missing native component ${name}`);
  for (const entry of operations)
    for (const [, name] of entry.matchAll(/native\.(\w+)/g)) {
      if (!exports.has(name)) throw new Error(`Missing native operation schema ${name}`);
    }
  // Remove once Orval emits schema/model type checks itself: https://github.com/orval-labs/orval/issues/4549
  const checks = names
    .map(
      (name) =>
        `  ${name}: [Assert<Extends<v.InferOutput<typeof ${name}Schema>, Models.${orvalTypeName(name)}>>, Assert<Extends<Models.${orvalTypeName(name)}, v.InferOutput<typeof ${name}Schema>>>];`,
    )
    .join("\n");
  return {
    native,
    schemas: `${header}import type * as v from "valibot";\nimport * as native from "./native";\nimport type * as Models from ${json(modelImport)};\n${names.map((name) => `export const ${name}Schema = native.${orvalTypeName(name)};`).join("\n")}\ntype Assert<T extends true> = T;\ntype Extends<A, B> = [A] extends [B] ? true : false;\nexport type SchemaModelTypeChecks = {\n${checks}\n};\n`,
    operations: `${header}import type * as v from "valibot";\nimport * as native from "./native";\nexport const apiV2Operations: Record<string, { public?: true; session?: true; request?: v.GenericSchema; responses: Record<string, Record<string, v.GenericSchema>> }> = {\n${operations.join(",\n")}\n};\n`,
  };
}

/** Writes the adapter output, then runs the same Biome check that Orval runs on its own output. */
export async function generateFiles(input: string, output: string): Promise<void> {
  const document = parseOpenApiDocument(await readFile(input, "utf8"));
  const result = generate(document, await readFile(resolve(output, "native.ts"), "utf8"));
  await mkdir(output, { recursive: true });
  const files = Object.entries(result).map(([name, source]) => ({
    path: resolve(output, `${name}.ts`),
    source,
  }));
  for (const { path, source } of files) await writeFile(path, source);
  execFileSync("pnpm", ["exec", "biome", "check", "--write", ...files.map(({ path }) => path)], { stdio: "inherit" });
}

