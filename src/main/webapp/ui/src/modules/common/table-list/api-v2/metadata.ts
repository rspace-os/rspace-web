import type * as v from "valibot";
import { apiV2CollectionMetadata } from "@/modules/common/api/v2/generated/tableListMetadata";
import type { FieldName, SortRule } from "@/modules/common/collection/config";
import type { FilterOperatorToken } from "@/modules/common/collection/filterOperators";
import type { RelationshipFilterPicker } from "@/modules/common/collection/relationshipFilterPicker";
import type {
  ApiV2PrimitiveFieldType,
  metadataFilterSchema,
  metadataWhereSchema,
  runtimeNamespaceSchema,
} from "./metadataSchemas";

export type { ApiV2PrimitiveFieldType };

export type ApiV2ParsedSelector = {
  readonly fieldType: ApiV2PrimitiveFieldType | null;
  readonly operators: readonly FilterOperatorToken[];
  readonly wildcards: boolean;
  readonly picker?: RelationshipFilterPicker;
  /** The published values of an enum selector. */
  readonly values?: readonly (string | number)[];
};

/** What a selector accepts in a filter: its operators and whether its values may hold wildcards. */
export type ApiV2SelectorContract = Pick<ApiV2ParsedSelector, "operators" | "wildcards">;

type ApiV2FilterSelector = Omit<ApiV2ParsedSelector, "fieldType"> & {
  readonly fieldType?: ApiV2ParsedSelector["fieldType"];
};

type FilterLimits = v.InferOutput<typeof metadataFilterSchema> & {
  maximumWhereLength: v.InferOutput<typeof metadataWhereSchema>["maxLength"];
};
export type ApiV2FilterLimits = { readonly [K in keyof FilterLimits]: FilterLimits[K] };

export type ApiV2RuntimeFieldNamespace = Readonly<Omit<v.InferOutput<typeof runtimeNamespaceSchema>, "viaResource">>;

/** Endpoint rules generated by the API V2 OpenAPI document. */
export type ApiV2CollectionMetadata<TDocument> = {
  resourceName: string;
  fields: readonly FieldName<TDocument>[];
  sorting: {
    fields: readonly FieldName<TDocument>[];
    default: readonly SortRule<TDocument>[];
    maximumFields: number;
  };
  filtering: {
    selectors: Readonly<Partial<Record<string, ApiV2FilterSelector>>>;
    limits: ApiV2FilterLimits;
  };
  runtimeFields?: readonly ApiV2RuntimeFieldNamespace[];
  pagination: {
    defaultLimit: number;
    maximumLimit: number;
  };
};

// Also checks at compile time that the generated constant has this shape.
const generated: Readonly<Record<string, ApiV2CollectionMetadata<Record<string, unknown>>>> = apiV2CollectionMetadata;

/** The generated metadata of a registry resource; a resource outside the registry must supply its own. */
export function apiV2CollectionMetadataFor<TDocument>(resourceName: string): ApiV2CollectionMetadata<TDocument> {
  const metadata = Object.hasOwn(generated, resourceName) ? generated[resourceName] : undefined;
  if (metadata === undefined) throw new Error(`No API v2 collection metadata for ${resourceName}`);
  // The generated entry lists the published fields as strings; the caller's document type names them.
  return metadata as ApiV2CollectionMetadata<TDocument>;
}
