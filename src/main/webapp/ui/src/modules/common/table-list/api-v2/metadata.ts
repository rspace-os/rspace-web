export type ApiV2FilterLimits = Omit<ApiV2ParsedFilterMetadata, "selectors"> & {
  maximumWhereLength: InferOutput<typeof metadataWhereSchema>["maxLength"];
};

type ApiV2FilterSelector = Omit<ApiV2ParsedSelector, "fieldType" | "operators"> & {
  fieldType?: ApiV2ParsedSelector["fieldType"];
  operators: Readonly<ApiV2ParsedSelector["operators"]>;
};

export type ApiV2StructuredField = {
  type: "array" | "object";
  fields: readonly FieldConfig<Record<string, unknown>>[];
  nullable: boolean;
  readOnly: boolean;
  minRows?: number;
  maxRows?: number;
};

/** Endpoint rules generated by the API V2 OpenAPI document. */
export type ApiV2CollectionMetadata<TDocument> = {
  resourceName: string;
  fields: readonly FieldName<TDocument>[];
  /** Declared embedded fields from Read properties, separate from relationship multiplicity. */
  structuredFields?: Readonly<Partial<Record<string, ApiV2StructuredField>>>;
  sorting: {
    fields: readonly FieldName<TDocument>[];
    default: readonly SortRule<TDocument>[];
    maximumFields: number;
  };
  filtering: {
    selectors: Readonly<Partial<Record<string, ApiV2FilterSelector>>>;
    limits: ApiV2FilterLimits;
  };
  runtimeFields?: readonly ApiV2RuntimeFieldNamespace[];
  pagination: {
    defaultLimit: number;
    maximumLimit: number;
  };
};

function parseAt<TSchema extends GenericSchema>(schema: TSchema, input: unknown, role: string): InferOutput<TSchema> {
  try {
    return parseOrThrow(schema, input);
  } catch (error) {
    throw new Error(`OpenAPI ${role}: ${error instanceof Error ? error.message : String(error)}`, { cause: error });
  }
}

function declaredChildren(
  children: readonly ApiV2MetadataChild[],
  parent: string,
): FieldConfig<Record<string, unknown>>[] {
  return children.map((child) => {
    const { name, type: schema, writeConstraints, openApi } = child;
    const path = `${parent}.${name}`;
    const common = {
      name,
      labelKey: name,
      label: openApi.title ?? name,
      required: child.requiredOnCreate,
      nullable: child.nullable,
      readOnly: child.readOnly,
      ...(child.defaultValue == null ? {} : { defaultValue: child.defaultValue }),
      writeConstraints,
    };
    if (schema.jsonType === "array" || schema.jsonType === "object") {
      if (child.fields.length === 0) throw new Error(`OpenAPI ${path} child fields: at least one child is required`);
      return {
        ...common,
        type: schema.jsonType,
        fields: declaredChildren(child.fields, path),
        ...(schema.jsonType === "array" ? parseAt(metadataRowBoundsSchema, writeConstraints, path) : {}),
      };
    }
    if (child.fields.length !== 0) throw new Error(`OpenAPI scalar field ${path} cannot declare child fields`);
    switch (schema.jsonType) {
      case "integer":
      case "number":
        return { ...common, type: "number" };
      case "boolean":
        return { ...common, type: "boolean" };
      case "string": {
        const options = writeConstraints.enum ?? schema.structure.enum;
        if (options !== undefined) return { ...common, type: "select", options };
        if ((openApi.format ?? schema.format) === "date-time") return { ...common, type: "dateTime" };
        const maximumLength = writeConstraints.maxLength ?? schema.maxLength;
        return { ...common, type: "text", ...(maximumLength == null ? {} : { maximumLength }) };
      }
      default:
        throw new Error(`OpenAPI ${path} has an unsupported field type`);
    }
  });
}

function structuredFields(properties: Record<string, Record<string, unknown>>): Record<string, ApiV2StructuredField> {
  return Object.fromEntries(
    Object.entries(properties)
      .filter(([, property]) => property["x-rspace-fields"] !== undefined)
      .map(([name, property]) => {
        const parsed = parseAt(metadataStructuredPropertySchema, property, name);
        const type = parsed.type;
        if (type !== "array" && type !== "object")
          throw new Error(`OpenAPI ${name} has x-rspace-fields on a scalar field`);
        return [
          name,
          {
            type,
            fields: declaredChildren(parsed["x-rspace-fields"], name),
            nullable: Array.isArray(property.type) && property.type.includes("null"),
            readOnly: parsed.readOnly,
            ...(type === "array" ? parseAt(metadataRowBoundsSchema, property, name) : {}),
          },
        ];
      }),
  );
}

function runtimeFieldNamespaces(declared: unknown, resourceName: string): ApiV2RuntimeFieldNamespace[] {
  const descriptors = parseAt(metadataRuntimeFieldsSchema, declared, `${resourceName} runtime fields`);
  const namespaces = new Set<string>();
  for (const descriptor of descriptors) {
    const { namespace, catalog, via } = descriptor;
    if (namespaces.has(namespace)) throw new Error(`Duplicate runtime field namespace ${namespace}`);
    namespaces.add(namespace);
    validateRuntimeFieldCatalogUrl(catalog);
    const parts = namespace.split(".");
    if (parts.at(-1) !== catalog.split("/").at(-1)) {
      throw new Error(`Runtime field namespace ${namespace} does not match its catalog`);
    }
    if ((parts.length === 1 && via !== "") || (parts.length === 2 && via !== parts[0])) {
      throw new Error(`Runtime field namespace ${namespace} has an unsupported relationship source`);
    }
  }
  return descriptors;
}

export function apiV2CollectionMetadataFromOpenApi<TDocument>(
  document: unknown,
  resourceName: string,
): ApiV2CollectionMetadata<TDocument> {
  const root = parseAt(metadataDocumentSchema, document, "document");
  const operation = parseAt(
    metadataOperationSchema,
    root.paths[`/api/v2/${resourceName}`],
    `${resourceName} list operation`,
  ).get;
  const parameter = (name: string) => {
    const found = operation.parameters.find((candidate) => candidate.name === name);
    if (!found) throw new Error(`OpenAPI list operation has no ${name} parameter`);
    return found;
  };
  const sort = parseAt(metadataSortSchema, parameter("sort")["x-rspace-sort"], `${resourceName} sort metadata`);
  const whereParameter = parameter("where");
  const { selectors, ...limits } = parseAt(
    metadataFilterSchema,
    whereParameter["x-rspace-filter"],
    `${resourceName} filter metadata`,
  );
  const where = parseAt(metadataWhereSchema, whereParameter.schema, `${resourceName} where schema`);
  const limit = parseAt(metadataLimitSchema, parameter("limit").schema, `${resourceName} limit schema`);
  const allowedFields = parseAt(
    metadataAllowedFieldsSchema,
    parameter("fields")["x-rspace-allowed-fields"],
    `${resourceName} allowed fields`,
  );
  const fields = allowedFields[resourceName];
  if (fields === undefined) throw new Error(`OpenAPI has no allowed fields for ${resourceName}`);
  const item = operation.responses["200"].content["application/json"].schema.properties.docs.items;
  const component = item.$ref.slice("#/components/schemas/".length);
  const definition = root.components.schemas[component];
  if (definition === undefined) throw new Error(`OpenAPI Read component ${component} was not found`);
  const read = parseAt(metadataReadSchema, definition, `${component} Read component`);
  return {
    resourceName,
    fields: fields as FieldName<TDocument>[],
    structuredFields: structuredFields(read.properties),
    sorting: {
      fields: sort.fields as FieldName<TDocument>[],
      default: sort.default.map(sortRuleFromToken<TDocument>),
      maximumFields: sort.maximumFields,
    },
    filtering: { selectors, limits: { ...limits, maximumWhereLength: where.maxLength } },
    runtimeFields: runtimeFieldNamespaces(whereParameter["x-rspace-runtime-fields"], resourceName),
    pagination: { defaultLimit: limit.default, maximumLimit: limit.maximum },
  };
}

async function fetchApiV2CollectionMetadata<TDocument>(
  resourceName: string,
  options: { fetch?: typeof globalThis.fetch; signal?: AbortSignal } = {},
): Promise<ApiV2CollectionMetadata<TDocument>> {
  const response = await (options.fetch ?? fetchWithUiToken)("/api/v2/openapi.json", {
    headers: { "X-Requested-With": "XMLHttpRequest" },
    signal: options.signal,
  });
  if (!response.ok) throw new Error(`API V2 OpenAPI request failed with status ${response.status}`);
  const document: unknown = await response.json();
  return apiV2CollectionMetadataFromOpenApi<TDocument>(document, resourceName);
}

export function apiV2MetadataOptions<T>(
  resource: string,
  options: { fetch?: typeof globalThis.fetch; metadata?: ApiV2CollectionMetadata<T> } = {},
) {
  return queryOptions({
    queryKey: apiV2MetadataKey(resource),
    queryFn: ({ signal }) =>
      options.metadata ?? fetchApiV2CollectionMetadata<T>(resource, { fetch: options.fetch, signal }),
    staleTime: Infinity,
    gcTime: Infinity,
  });
}
