import { describe, expect, test, vi } from "vitest";
import "@/__tests__/__mocks__/matchMedia";
import { render, screen, waitFor } from "@testing-library/react";
import MockAdapter from "axios-mock-adapter";
import { renderWithRealI18n } from "@/__tests__/helpers/realI18n";
import { PHISHING_DESCRIPTION } from "@/__tests__/mocks/inventoryRichTextMocks";
import axios from "@/common/axios";
import publicEn from "@/modules/common/i18n/locales/en-US/public.json";
import { mockIGSNAttrs, mockIGSNIdentifier } from "../../../Inventory/components/Fields/Identifiers/__tests__/mocking";
import IdentifierPublicPage, { IdentifierDataGrid } from "../IdentifierPublicPage";

vi.mock("../../../Inventory/components/Fields/Identifiers/MapViewer", () => {
  const MockMapViewer = () => <></>;
  MockMapViewer.displayName = "MockMapViewer";
  return { default: MockMapViewer };
});

const mockAxios = new MockAdapter(axios);
describe("IdentifierPublicPage", () => {
  describe("Optional Fields", () => {
    test("Should render dates correctly", async () => {
      const identifier = mockIGSNAttrs();
      identifier.dates = [
        {
          value: "2024-09-05T12:56:35.965Z",
          type: "ACCEPTED",
        },
      ];
      mockAxios.onGet("/api/inventory/v1/public/view/1").reply(200, {
        identifiers: [identifier],
        description: null,
        tags: [],
      });

      render(<IdentifierPublicPage publicId={"1"} />);
      await waitFor(() => {
        expect(screen.getByText("public:headings.dates")).toBeVisible();
      });
      expect(screen.getByRole("group", { name: "public:labels.dates" })).toMatchTextContent("2024-09-05");
    });
  });

  describe("Description", () => {
    test("shows the description without its form controls", async () => {
      mockAxios.onGet("/api/inventory/v1/public/view/1").reply(200, {
        identifiers: [{ ...mockIGSNAttrs(), customFieldsOnPublicPage: true }],
        description: PHISHING_DESCRIPTION,
        tags: [],
      });

      render(<IdentifierPublicPage publicId={"1"} />);

      expect(await screen.findByText("Calibrated light microscope.")).toBeInTheDocument();
      expect(screen.queryByRole("button", { name: "Sign in" })).not.toBeInTheDocument();
    });
  });

  test("renders publisher metadata as text instead of an external link", async () => {
    const identifier = mockIGSNIdentifier("sample");
    identifier.publisher = 'Institution<externalLink href="https://attacker.example">Verify record</externalLink>';

    await renderWithRealI18n(<IdentifierDataGrid identifier={identifier} record={{ description: null, tags: [] }} />, {
      resources: { public: publicEn },
      defaultNS: "public",
    });

    expect(screen.queryAllByRole("link", { name: "Verify record" })).toHaveLength(0);
    const footer = screen.getByText(
      (content) =>
        content.includes("If you wish to obtain more information about this item") &&
        content.includes("This page was generated by") &&
        content.includes(identifier.publisher),
    );
    expect(footer).toBeVisible();
    expect(footer).toMatchTextContent(
      `If you wish to obtain more information about this item, please contact the research data management department at ${identifier.publisher}.`,
    );
    expect(footer).toMatchTextContent(`This page was generated by ${identifier.publisher} using RSpace Public Pages.`);
  });
});
