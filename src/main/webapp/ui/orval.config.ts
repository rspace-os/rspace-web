import { readFileSync } from "node:fs";
import { defineConfig, jsDoc, type OpenApiInfoObject } from "orval";
import { buildInvalidationRules, getOperations } from "./scripts/api-v2-invalidation";
import { filteredWhereOperations } from "./scripts/api-v2-valibot/filters";
import { mutatorOverrides as deriveMutatorOverrides } from "./scripts/api-v2-valibot/mutators";
import { parseOpenApiDocument } from "./scripts/api-v2-valibot/openapi";
import { crossResourceInvalidation } from "./src/modules/common/api/v2/crossResourceInvalidation";

const spec = parseOpenApiDocument(
  readFileSync(new URL("./src/modules/common/api/v2/openapi.generated.json", import.meta.url), "utf8"),
);
// Binary successes select apiV2BlobFetch from the spec; operations whose response headers (ETag, Location) callers
// read are listed here. Every operation declaring an ETag is either listed or excluded explicitly.
const mutatorOverrides = deriveMutatorOverrides(spec, {
  headers: [
    "getAdminBookingSettings",
    "patchAdminBookingSettings",
    "getBookingCalendarSubscription",
    "createBookingCalendarSubscription",
    "rotateBookingCalendarSubscription",
    "getUserBookingCalendarSubscription",
    "createUserBookingCalendarSubscription",
    "rotateUserBookingCalendarSubscription",
    "getMyBookingNotificationSubscription",
    "replaceMyBookingNotificationSubscription",
  ],
  // These take If-Match from the body `version` instead of the ETag header.
  etagExclusions: [
    "getApiV2OpenApiDocument",
    "getBookingConfigurationAccess",
    "replaceBookingConfigurationAccess",
    "getBookingSettings",
  ],
});
// Collection operations whose `where` carries filter metadata also accept a typed where object.
const whereObjectOperations = filteredWhereOperations(spec);
const operations = Object.fromEntries(
  getOperations(spec).map(({ operationId }) => [
    operationId,
    {
      requestOptions: { operationId },
      ...(whereObjectOperations.has(operationId)
        ? {
            paramsSerializer: {
              path: "./src/modules/common/api/v2/apiV2SerializeQuery.ts",
              name: "apiV2SerializeQuery",
            },
          }
        : {}),
      ...(Object.hasOwn(mutatorOverrides, operationId)
        ? {
            mutator: {
              path: "./src/modules/common/api/v2/apiV2Fetch.ts",
              name: mutatorOverrides[operationId],
              inferred: true,
            },
          }
        : {}),
    },
  ]),
);

// Orval types bodiless responses, such as 304 Not Modified, as `void` in error unions and will keep doing so
// (https://github.com/orval-labs/orval/issues/4568, closed as not planned). As its maintainers suggest, each generated
// file suppresses the rule in its header; `biome-ignore-all` only works on a file's first line, so it precedes the banner.
const generatedFileHeader = ({ title, description, version }: OpenApiInfoObject) =>
  [
    "// biome-ignore-all lint/suspicious/noConfusingVoidType: Orval types bodiless responses as void (orval-labs/orval#4568)",
    jsDoc({
      description: [
        "Generated by orval 🍺",
        "Do not edit manually.",
        ...(title ? [title] : []),
        ...(description ? [description] : []),
        ...(version ? [`OpenAPI spec version: ${version}`] : []),
      ],
    }),
  ].join("\n");

// REST API v2 date-times are Temporal instants: models type them, the Valibot schemas decode them and generated
// URLs encode them with the API's three-digit wire form.
const temporalImport = { name: "Temporal", importPath: "@js-temporal/polyfill" };
const formatType = {
  "date-time": {
    type: "Temporal.Instant",
    import: temporalImport,
    decode: "Temporal.Instant.from",
    decodeImport: temporalImport,
    encode: "instantToWire",
    encodeImport: { name: "instantToWire", importPath: "@/modules/common/time/instant" },
  },
};

export default defineConfig({
  api: {
    input: { target: "./src/modules/common/api/v2/openapi.generated.json" },
    output: {
      target: "./src/modules/common/api/v2/generated/api.ts",
      schemas: "./src/modules/common/api/v2/generated/models",
      headers: true,
      mode: "tags-split",
      client: "react-query",
      httpClient: "fetch",
      clean: true,
      formatter: "biome",
      override: {
        header: generatedFileHeader,
        enumGenerationType: "union",
        formatType,
        mutator: { path: "./src/modules/common/api/v2/apiV2Fetch.ts", name: "apiV2Fetch" },
        fetch: { includeHttpResponseReturnType: false, arrayFormat: "repeat" },
        query: {
          version: 5,
          useSuspenseQuery: true,
          signal: true,
          useInvalidate: true,
          mutationInvalidates: buildInvalidationRules(spec, crossResourceInvalidation),
        },
        operations,
      },
    },
  },
  validation: {
    input: { target: "./src/modules/common/api/v2/openapi.generated.json" },
    output: {
      client: "valibot",
      mode: "single",
      target: "./src/modules/common/api/v2/generated/valibot/native.ts",
      formatter: "biome",
      override: { formatType, valibot: { generateReusableSchemas: true } },
    },
  },
});
